if __name__ == "__main__":

    source_document = """
    Artificial intelligence is used in healthcare.
    AI can help doctors analyze medical images.
    Machine learning can detect patterns in patient data.
    AI systems can support doctors in making decisions.
    """

    generated_claims = [
        "Artificial intelligence is used in healthcare.",
        "AI can analyze medical images.",
        "AI completely replaces doctors.",
        "Machine learning detects patterns in patient data."
    ]

    verifier = DocumentVerifier(threshold=0.70)

    report = verifier.verify_claims(
        source_document,
        generated_claims
    )

    print("\n===== DOCUMENT VERIFICATION REPORT =====\n")

    for item in report:

        print("Claim:", item["claim"])
        print("Source:", item["source_reference"])
        print("Similarity:", item["similarity_score"])
        print("Status:", item["status"])
        print("-" * 50)